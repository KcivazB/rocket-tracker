  var lang = 'fr';
  var plurals = {};

  function pick(entry) {
    var i = LANGS.indexOf(lang);
    var v = entry[i < 0 ? 0 : i];
    return v == null ? entry[0] : v;
  }
  /** Translates key; params fill {placeholders}, params.n picks the plural form. Unknown keys return the key. */
  function t(key, params) {
    var entry = M[key];
    if (!entry) return key;
    var v = pick(entry);
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      var n = params && typeof params.n === 'number' ? params.n : 0;
      var pr = plurals[lang] || (plurals[lang] = typeof Intl !== 'undefined' && Intl.PluralRules ? new Intl.PluralRules(LOCALES[lang]) : null);
      var form = pr ? pr.select(n) : (n === 1 ? 'one' : 'other');
      v = v[form] != null ? v[form] : v.other;
    }
    if (typeof v !== 'string' || !params) return v;
    return v.replace(/\{(\w+)\}/g, function (m, k) { return params[k] != null ? String(params[k]) : m; });
  }
  function has(key) { return Object.prototype.hasOwnProperty.call(M, key); }
  function setLang(l) { if (LANGS.indexOf(l) >= 0) lang = l; return lang; }
  function getLang() { return lang; }
  function locale() { return LOCALES[lang]; }

  /** Saved choice, else the browser language (French when it is French, English otherwise). */
  function detect() {
    try {
      var saved = root.localStorage && root.localStorage.getItem('rt.lang');
      if (LANGS.indexOf(saved) >= 0) return saved;
    } catch (e) { /* storage unavailable */ }
    var nav = (root.navigator && (root.navigator.languages || [root.navigator.language])) || [];
    for (var i = 0; i < nav.length; i++) {
      var base = String(nav[i] || '').slice(0, 2).toLowerCase();
      if (LANGS.indexOf(base) >= 0) return base;
    }
    return 'en';
  }
  function save(l) { try { root.localStorage.setItem('rt.lang', l); } catch (e) { /* ignore */ } }

  /** Translates the static page: data-i18n (text), data-i18n-html (trusted markup from this file),
   *  data-i18n-attr="placeholder:key;title:key". */
  function apply(el) {
    var q = function (sel) { return Array.prototype.slice.call((el || root.document).querySelectorAll(sel)); };
    q('[data-i18n]').forEach(function (n) { n.textContent = t(n.getAttribute('data-i18n')); });
    q('[data-i18n-html]').forEach(function (n) { n.innerHTML = t(n.getAttribute('data-i18n-html')); });
    q('[data-i18n-attr]').forEach(function (n) {
      n.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        var p = pair.split(':');
        if (p.length === 2) n.setAttribute(p[0].trim(), t(p[1].trim()));
      });
    });
    if (root.document && root.document.documentElement) root.document.documentElement.lang = lang;
  }

  var api = { t: t, has: has, setLang: setLang, getLang: getLang, locale: locale, detect: detect, save: save, apply: apply,
    LANGS: LANGS, messages: M };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  root.RT_I18N = api;
